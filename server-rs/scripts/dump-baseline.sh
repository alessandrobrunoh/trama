#!/usr/bin/env bash
# Regenerates crates/migration/src/baseline.sql from a database that the NestJS (TypeORM)
# migrations brought to the target schema.
#
#   scripts/dump-baseline.sh <container> <database> <last TypeORM migration name>
#   scripts/dump-baseline.sh delta-postgres trama IssueThreadUrl1793880000000
#
# The output holds the schema (no data) plus the TypeORM `migrations` rows up to and including the
# named migration, so the NestJS API treats a database created by the Rust baseline as migrated.
# Update `LAST_TYPEORM_MIGRATION` in crates/migration/src/m20261125_000001_baseline.rs to match.
set -euo pipefail

container=${1:?container}
database=${2:?database}
until=${3:?last TypeORM migration name}
out="$(dirname "$0")/../crates/migration/src/baseline.sql"

psql() { docker exec "$container" psql -U delta -d "$database" -v ON_ERROR_STOP=1 -tA "$@"; }

last_id=$(psql -c "select id from migrations where name = '$until'")
if [ -z "$last_id" ]; then
  echo "migration $until is not applied in $database" >&2
  exit 1
fi

{
  echo "-- Schema of the Trama database as left by the TypeORM migrations up to $until."
  echo "-- Generated by scripts/dump-baseline.sh; do not edit by hand."
  echo
  # Drop psql meta-commands, session settings (the search_path reset would leak into the
  # migrator's connection) and dump comments; every name is schema-qualified already.
  docker exec "$container" pg_dump -U delta -d "$database" --schema-only --no-owner \
    --no-privileges --no-comments \
    | grep -v -E '^\\(un)?restrict ' \
    | grep -v -E '^SET |^SELECT pg_catalog\.set_config' \
    | grep -v -E '^--' \
    | cat -s
  echo
  echo "-- TypeORM bookkeeping: the NestJS API skips these migrations."
  psql -c "select format('INSERT INTO public.migrations (id, \"timestamp\", name) VALUES (%s, %s, %L);', id, \"timestamp\", name) from migrations where id <= $last_id order by id"
  echo "SELECT pg_catalog.setval('public.migrations_id_seq', $last_id, true);"
} > "$out"

echo "wrote $out"
