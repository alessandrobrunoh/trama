#!/usr/bin/env node
/**
 * Regenerates `src/app/ui/icons/lucide.ts`.
 *
 * Every `Lucide<Name>` class in `@lucide/angular` is a full Angular component that carries its own
 * copy of the compiled SVG template (~3.3 kB each once minified). The app only ever passes icons to
 * `<svg [lucideIcon]="…">`, which accepts plain icon data, so this file ships the data only and the
 * template exists once (in `LucideDynamicIcon`).
 *
 * The script scans `src/` for icons imported from `@lucide/angular` and writes their data. An icon that
 * is not generated yet still works (it falls back to the library class) but costs ~3.3 kB, so run
 *
 *   node scripts/generate-lucide-icons.mjs
 *
 * after adding a new icon import. `node scripts/check-bundle-size.mjs` reports the initial size.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'src/app/ui/icons/lucide.ts');
const lib = readFileSync(
  join(root, 'node_modules/@lucide/angular/fesm2022/lucide-angular.mjs'),
  'utf8',
);

function walk(dir, out = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) walk(path, out);
    else if (path.endsWith('.ts') && path !== target) out.push(path);
  }
  return out;
}

const used = new Set();
for (const file of walk(join(root, 'src'))) {
  const text = readFileSync(file, 'utf8');
  for (const match of text.matchAll(
    /import\s*(?:type\s*)?\{([^}]*)\}\s*from\s*'@lucide\/angular'/g,
  )) {
    for (const part of match[1].split(',')) {
      const name = part
        .trim()
        .replace(/^type\s+/, '')
        .replace(/\s+as\s+.*/, '');
      if (/^Lucide[A-Z]/.test(name)) used.add(name);
    }
  }
}

const aliases = new Map();
for (const match of lib.matchAll(/^const (Lucide\w+) = (Lucide\w+);$/gm))
  aliases.set(match[1], match[2]);

const icons = new Map();
function iconData(name) {
  if (icons.has(name)) return icons.get(name);
  const start = lib.indexOf(`var ${name} = class ${name} extends LucideIconBase {`);
  if (start < 0) return null;
  const marker = lib.indexOf('static icon = ', start);
  if (marker < 0 || marker - start > 200) return null; // not an icon (e.g. LucideDynamicIcon)
  const from = marker + 'static icon = '.length;
  const to = lib.indexOf(';\n\ticon = signal(', from);
  const data = new Function(`return (${lib.slice(from, to)});`)();
  icons.set(name, data);
  return data;
}

const literal = (value) => {
  if (Array.isArray(value)) return `[${value.map(literal).join(', ')}]`;
  if (value && typeof value === 'object') {
    return `{ ${Object.entries(value)
      .map(([k, v]) => `${/^[A-Za-z_$][\w$]*$/.test(k) ? k : `'${k}'`}: ${literal(v)}`)
      .join(', ')} }`;
  }
  return typeof value === 'string'
    ? `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`
    : String(value);
};

const concrete = new Set();
const aliasOut = new Map();
const skipped = [];
for (const name of [...used].sort()) {
  const real = aliases.get(name) ?? name;
  if (iconData(real)) {
    concrete.add(real);
    if (real !== name) aliasOut.set(name, real);
  } else skipped.push(name);
}

const lines = [...concrete]
  .sort()
  .map((name) => `export const ${name}: LucideIconData = ${literal(iconData(name))};`);
const aliasLines = [...aliasOut]
  .sort()
  .map(([a, b]) => `export const ${a}: LucideIconData = ${b};`);

const out = `// GENERATED by scripts/generate-lucide-icons.mjs. Do not edit by hand.
//
// Icon data for the icons the app uses, exposed under the names \`@lucide/angular\` exports (tsconfig
// maps that specifier here). Unlisted names fall through to the library's own components. See the script.
import type { LucideIconData, LucideIcon as LucideIconComponent } from '@lucide/angular-lib';

export * from '@lucide/angular-lib';

/** Plain icon data (cheap) or, for icons not generated yet, the library's icon component. */
export type LucideIcon = LucideIconData | LucideIconComponent;

${lines.join('\n')}
${aliasLines.length ? `\n${aliasLines.join('\n')}\n` : ''}`;

writeFileSync(target, out);
console.log(
  `${relative(root, target)}: ${concrete.size} icons, ${aliasOut.size} aliases` +
    (skipped.length ? `, not icons (left to the library): ${skipped.join(', ')}` : ''),
);
